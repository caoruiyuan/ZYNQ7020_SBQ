#ifndef Q3_ANALYSIS_CONTROL_H
#define Q3_ANALYSIS_CONTROL_H

#define Q3_ANALYSIS_COMPONENT_THRESHOLD_DISABLED_TENTHS_PERCENT 0U
#define Q3_ANALYSIS_COMPONENT_THRESHOLD_MIN_TENTHS_PERCENT      1U
#define Q3_ANALYSIS_COMPONENT_THRESHOLD_MAX_TENTHS_PERCENT      100U
#define Q3_ANALYSIS_COMPONENT_THRESHOLD_DEFAULT_TENTHS_PERCENT  20U
#define Q3_ANALYSIS_COMPONENT_THRESHOLD_TENTHS_PER_PERCENT      10U

#define Q3_ANALYSIS_COMPONENT_THRESHOLD_TENTHS_PERCENT_IS_VALID(value) \
    (((value) == \
      Q3_ANALYSIS_COMPONENT_THRESHOLD_DISABLED_TENTHS_PERCENT) || \
     (((value) >= \
       Q3_ANALYSIS_COMPONENT_THRESHOLD_MIN_TENTHS_PERCENT) && \
      ((value) <= \
       Q3_ANALYSIS_COMPONENT_THRESHOLD_MAX_TENTHS_PERCENT)))

#define Q3_ANALYSIS_THRESHOLD_STATUS_IDLE    0U
#define Q3_ANALYSIS_THRESHOLD_STATUS_APPLIED 1U
#define Q3_ANALYSIS_THRESHOLD_STATUS_INVALID 2U

#endif /* Q3_ANALYSIS_CONTROL_H */
